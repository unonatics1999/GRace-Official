// Writes prisma/postgres/schema.prisma: the same data model as prisma/schema.prisma, for PostgreSQL.
// Local development stays on SQLite; the live site (Vercel + Supabase) builds with this copy.
//   DATABASE_URL = Supabase pooled connection (port 6543, ?pgbouncer=true&connection_limit=1)
//   DIRECT_URL   = Supabase direct connection (port 5432), used to create and update tables
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("prisma/schema.prisma", "utf8");
const datasource = /datasource db \{[\s\S]*?\}/;
if (!datasource.test(source)) throw new Error("No datasource block found in prisma/schema.prisma");

const postgres = source.replace(
  datasource,
  'datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")\n}',
);
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", `// GENERATED by scripts/postgres-schema.mjs from prisma/schema.prisma. Do not edit.\n${postgres}`);
console.log("Wrote prisma/postgres/schema.prisma");
